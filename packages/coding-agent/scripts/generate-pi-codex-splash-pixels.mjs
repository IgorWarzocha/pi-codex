import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadPhoton } from "../../ai/src/utils/photon.ts";

const directory = dirname(fileURLToPath(import.meta.url));
const inputPath = join(directory, "..", "src", "modes", "interactive", "assets", "pi-codex-duo.png");
const outputPath = join(
	directory,
	"..",
	"src",
	"modes",
	"interactive",
	"components",
	"pi-codex-splash-pixels.generated.ts",
);
const width = 32;
const height = 24;

const photon = await loadPhoton();
if (!photon) throw new Error("Photon is required to generate Pi-Codex terminal splash pixels");

const source = photon.PhotonImage.new_from_byteslice(await readFile(inputPath));
const image = photon.resize(source, width, height, photon.SamplingFilter.Nearest);
const pixels = Buffer.from(image.get_raw_pixels()).toString("base64");
source.free();
image.free();

const chunks = pixels.match(/.{1,96}/g) ?? [];
const output = `// Generated by scripts/generate-pi-codex-splash-pixels.mjs. Do not edit.\n\nexport const PI_CODEX_SPLASH_PIXEL_WIDTH = ${width};\nexport const PI_CODEX_SPLASH_PIXEL_HEIGHT = ${height};\nexport const PI_CODEX_SPLASH_PIXELS_BASE64 = [\n${chunks.map((chunk) => `\t"${chunk}",`).join("\n")}\n].join("");\n`;

if (process.argv.includes("--check")) {
	const current = await readFile(outputPath, "utf8").catch(() => undefined);
	if (current !== output) throw new Error(`${outputPath} is out of date; run npm run generate:splash-pixels`);
} else {
	await writeFile(outputPath, output);
}
